const runMigrations = (db, fromVersion, toVersion) => {
  console.log(`[Schema] Running migrations from v${fromVersion} to v${toVersion}...`);
  // Future: add migration steps here, e.g.:
  // if (fromVersion < 2) applyV2(db);
  // if (fromVersion < 3) applyV3(db);
  db.prepare('INSERT INTO schema_version (version) VALUES (?)').run(toVersion);
  console.log(`[Schema] Migrated to v${toVersion}.`);
};

/**
 * getSchemaVersion() ΓÇö read current schema version from DB
 * Returns null if not yet initialized.
 */
const getSchemaVersion = (db) => {
  try {
    const row = db.prepare('SELECT MAX(version) as v FROM schema_version').get();
    return row ? row.v : null;
  } catch {
    return null;
  }
};

module.exports = { createSchema, getSchemaVersion, SCHEMA_VERSION };
